"""Load the shared Indiana CXR tables and resolve source/cache image files."""

from functools import lru_cache
import os
from pathlib import Path

import pandas as pd
from PIL import Image
from torch.utils.data import Dataset

from src.config import DATASET_ROOT, INDIANA_SLUG, SHARED

_IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"}


def _canonicalize(df: pd.DataFrame) -> pd.DataFrame:
    """Map the Qwen notebook's schema and the legacy project schema to one API."""
    df = df.copy()
    if "uid" not in df:
        raise ValueError("Dataset table must contain a 'uid' study identifier.")

    if "target_text" not in df:
        for candidate in ("processed_report", "report_combined", "findings"):
            if candidate in df:
                df["target_text"] = df[candidate]
                break
    if "target_text" not in df:
        raise ValueError(
            "Dataset table needs one of: target_text, processed_report, "
            "report_combined, or findings."
        )

    if "filename" not in df:
        for candidate in ("frontal_img", "image_path"):
            if candidate in df:
                df["filename"] = df[candidate]
                break
    if "filename" not in df and "image" not in df:
        raise ValueError("Dataset table needs an image 'filename' or 'image_path'.")
    if "filename" not in df:
        df["filename"] = df["image"]

    for column in ("target_text", "indication", "filename"):
        if column not in df:
            df[column] = ""
        df[column] = df[column].fillna("").astype(str)
    df["uid"] = df["uid"].astype(str)
    return df


def load_table(split=None, shared_dir=None):
    """Load dataset.csv or the persisted train/val/test table from Drive.

    Both ``val`` and ``validation`` are accepted. Split files are preferred so
    the exact patient/study split generated by notebook 09 is reused.
    """
    root = Path(shared_dir) if shared_dir is not None else SHARED
    if split is None:
        table_path = root / "dataset.csv"
    else:
        normalized = {"validation": "val", "valid": "val"}.get(str(split).lower(), str(split).lower())
        if normalized not in {"train", "val", "test"}:
            raise ValueError("split must be None, 'train', 'val'/'validation', or 'test'.")
        table_path = root / f"{normalized}.csv"
        if not table_path.exists():
            table_path = root / "dataset.csv"

    if not table_path.exists():
        raise FileNotFoundError(
            f"Shared table not found: {table_path}. Run notebook 09 through "
            "'Save splits' first, or run notebook 01 to prepare the shared data."
        )
    df = _canonicalize(pd.read_csv(table_path))
    if split is not None and "split" in df.columns and table_path.name == "dataset.csv":
        normalized = {"validation": "val", "valid": "val"}.get(str(split).lower(), str(split).lower())
        df["split"] = df["split"].replace({"validation": "val"})
        df = df[df["split"].astype(str).str.lower() == normalized]
    return df.reset_index(drop=True)


@lru_cache(maxsize=1)
def _image_index():
    """Build a filename index only when the Drive image cache is unavailable."""
    if DATASET_ROOT:
        root = Path(DATASET_ROOT)
    elif os.environ.get("CXR_ALLOW_DATASET_DOWNLOAD") == "1":
        try:
            import kagglehub
        except ImportError as exc:
            raise RuntimeError(
                "Install kagglehub or set CXR_DATASET_ROOT to the extracted "
                "Indiana dataset directory."
            ) from exc
        root = Path(kagglehub.dataset_download(INDIANA_SLUG))
    else:
        raise RuntimeError(
            "Set CXR_DATASET_ROOT to the existing Indiana dataset folder. "
            "Automatic download is disabled; to explicitly allow KaggleHub "
            "download, set CXR_ALLOW_DATASET_DOWNLOAD=1."
        )
    if not root.exists():
        raise FileNotFoundError(f"Dataset directory does not exist: {root}")
    return {p.name: p for p in root.rglob("*") if p.is_file() and p.suffix.lower() in _IMAGE_SUFFIXES}


def resolve_image(row, size=224, shared_dir=None):
    """Resolve image from the normalized Drive cache, a table path, or Kaggle."""
    root = Path(shared_dir) if shared_dir is not None else SHARED
    uid = str(row["uid"])
    cached = root / f"img{size}" / f"{uid}.png"
    if cached.is_file():
        return cached

    raw = str(row.get("filename", "")).strip()
    if raw:
        candidate = Path(raw)
        if candidate.is_file():
            return candidate
        # The Indiana table stores image basenames, while KaggleHub holds them
        # under images_normalized/ or images/ nested directories.
        indexed = _image_index().get(candidate.name)
        if indexed is not None:
            return indexed
    raise FileNotFoundError(
        f"Could not find image for uid={uid!r}, filename={raw!r}. Looked for "
        f"{cached} and searched the configured Indiana dataset directory."
    )


class CXRDataset(Dataset):
    def __init__(self, split, size=224, transform=None, shared_dir=None):
        self.df = load_table(split, shared_dir=shared_dir)
        self.size = size
        self.transform = transform
        self.shared_dir = shared_dir

    def __len__(self):
        return len(self.df)

    def __getitem__(self, i):
        row = self.df.iloc[i]
        image_path = resolve_image(row, self.size, self.shared_dir)
        with Image.open(image_path) as source:
            image = source.convert("L").copy()
        if self.transform:
            image = self.transform(image)
        return {
            "image": image,
            "indication": row["indication"],
            "target_text": row["target_text"],
            "uid": row["uid"],
            "filename": row["filename"],
        }
